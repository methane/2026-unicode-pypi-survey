PUB = Path(__file__).resolve().parent.parent
PRIMARY = ['PyUnicode_New', 'PyUnicode_WRITE', 'PyUnicode_WriteChar',
           'PyUnicode_CopyCharacters', 'PyUnicode_Fill']
ORIGINAL_READ = ['PyUnicode_DATA', 'PyUnicode_1BYTE_DATA', 'PyUnicode_2BYTE_DATA',
                 'PyUnicode_4BYTE_DATA', 'PyUnicode_KIND', 'PyUnicode_READ', 'PyUnicode_READ_CHAR']
EXPANDED_READ = ['PyUnicode_ReadChar', 'PyUnicode_AS_UNICODE', 'PyUnicode_AS_DATA',
                 'PyUnicode_AsUnicode', 'PyUnicode_AsUnicodeAndSize', 'PyUnicode_AsUCS4',
                 'PyUnicode_AsUCS4Copy']
ORIGINAL_TOKEN = re.compile(rb'(?<![A-Za-z0-9_])(?:' + b'|'.join(s.encode() for s in PRIMARY + ORIGINAL_READ)
                            + rb'|_?PyUnicodeWriter_[A-Za-z0-9_]+)(?![A-Za-z0-9_])')
TOKEN = re.compile(rb'(?<![A-Za-z0-9_])(?:' + b'|'.join(s.encode() for s in PRIMARY + ORIGINAL_READ + EXPANDED_READ)
                   + rb'|_?PyUnicodeWriter_[A-Za-z0-9_]+|__Pyx_PyUnicode_(?:READ_CHAR|READ|DATA|KIND|1BYTE_DATA|2BYTE_DATA|4BYTE_DATA))(?![A-Za-z0-9_])')
BROAD = re.compile(rb'PyUnicode|PyASCIIObject|PyCompactUnicodeObject|Py_UCS[124]|Py_UNICODE|PyUnicodeObject|unicodeobject')
LAYOUT = re.compile(rb'Py(?:ASCII|CompactUnicode|Unicode)Object')
# Victor Stinner misc/search_pypi_top.py f1ba71b20c650f0e63920fe6f25292794c38f94a.
# These are filename endswith filters, not source/provenance classifications.
IGNORED = tuple('.' + x.lower() for x in (
    'EXE','SO','PYD','PYC','WHL','BZ2','CAB','GZ','ZIP','RAR','TAR','TGZ','XZ',
    'AI','BMP','ICO','JPG','PNG','PSD','SVG','TGA','TIF','WMF','XCF','AAC','AIF',
    'ANI','MP3','WAV','WMA','AVI','MKV','MP4','DEB','RPM','BIN','PDF','MO','DB',
    'ISO','JAR','TTF','XLS','DS_Store','JS','JS.MAP','JSON','RST','HTML','CSS'))
TEXTCHARS = bytearray({7,8,9,10,12,13,27} | set(range(0x20,0x100)) - {0x7f})
CYTHON = re.compile(br'^/\* Generated by Cython [0-9]+(.[0-9]+)+ ')
NATIVE = CODE_EXT - {'.py'}
FORMAT_VERSION = 1

def utc():
    return datetime.datetime.now(datetime.timezone.utc).isoformat()

def save_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    temporary.replace(path)

def file_hash(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()

def safe_name(name):
    parts = PurePosixPath(name).parts
    return bool(name) and not PurePosixPath(name).is_absolute() and '..' not in parts and '\\' not in name and not re.search(r'[\x00-\x1f\x7f]', name) and not re.match(r'^[A-Za-z]:', name)

def scan_text(data, name, package, version):
    """One record per lexical token; do not infer function/read behavior here."""
    if b'PyUnicode' not in data:
        return []
    matches = list(TOKEN.finditer(data))
    if not matches:
        return []
    suffix = PurePosixPath(name).suffix.lower()
    text = data.decode('latin1')  # Preserves exact byte offsets for lexical masking.
    masked = mask_source(text, suffix)
    digest = hashlib.sha256(data).hexdigest()
    line_offsets = [m.start() for m in re.finditer('\n', text)]
    default_included = PurePosixPath(name).name != 'pythoncapi_compat.h' and not CYTHON.match(data.split(b'\n', 1)[0])
    cython_included = PurePosixPath(name).name != 'pythoncapi_compat.h'
    file_origin = origin(name, text)
    hits = []
    for match in matches:
        start, end = match.span()
        hits.append({'package': package, 'version': version, 'path': name,
                     'symbol': match.group().decode('ascii'), 'line': bisect.bisect_left(line_offsets, start) + 1,
                     'byte_offset': start, 'kind': kind_of(text, masked, start, end, suffix),
                     'origin': file_origin, 'file_sha256': digest,
                     'canonical_default_included': default_included,
                     'canonical_cython_included': cython_included,
                     'original_write_scope': bool(ORIGINAL_TOKEN.fullmatch(match.group()))})
    return hits

def scan_archive(path, package, version=None, retain='none', source_root=None, max_member_bytes=128 * 1024**2):
    """Read regular members directly; never extract archive paths or follow links."""
    record = {'regular_members': 0, 'declared_bytes': 0, 'files_inspected': 0,
              'hits': [], 'candidate_files': [], 'native_files': [], 'skipped_members': [],
              'links': [], 'filter_counts': {}, 'retained_source_files': 0}
    filtered = collections.Counter()
    def consume(name, size, factory):
        record['regular_members'] += 1
        record['declared_bytes'] += size
        if not safe_name(name):
            record['skipped_members'].append({'path': name, 'bytes': size, 'reason': 'unsafe_member_name'})
            return
        if name.lower().endswith(IGNORED):
            filtered['upstream_filename_filter'] += 1
            return
        if size > max_member_bytes:
            record['skipped_members'].append({'path': name, 'bytes': size, 'reason': 'text_member_size_limit', 'limit_bytes': max_member_bytes})
            return
        with factory() as stream:
            data = stream.read(size + 1)
        if len(data) != size:
            raise ValueError('archive member size mismatch: ' + name)
        record['files_inspected'] += 1
        if data[:256].translate(None, TEXTCHARS):
            filtered['upstream_first256_binary_filter'] += 1
            return
        suffix = PurePosixPath(name).suffix.lower()
        broad = bool(BROAD.search(data))
        native = suffix in NATIVE or bool(re.search(r'\.(?:c|h|cc|cpp|cxx|hpp)(?:\.in|\.src)$', name, re.I))
        if not (native or broad):
            return
        digest = hashlib.sha256(data).hexdigest()
        row = {'package': package, 'version': version, 'path': name, 'sha256': digest,
               'bytes': size, 'origin': origin(name, data.decode('latin1')),
               'canonical_default_included': PurePosixPath(name).name != 'pythoncapi_compat.h' and not CYTHON.match(data.split(b'\n', 1)[0]),
               'canonical_cython_included': PurePosixPath(name).name != 'pythoncapi_compat.h',
               'has_unicode_indicators': broad, 'raw_layout_candidate': bool(LAYOUT.search(data))}
        record['native_files'].append(row)
        hits = scan_text(data, name, package, version) if broad else []
        record['hits'].extend(hits)
        if broad:
            record['candidate_files'].append(row)
        # Metadata and hits are default output; source bytes require explicit opt-in.
        if retain == 'native' or retain == 'candidates' and broad:
            safe_suffix = suffix if suffix in CODE_EXT else '.txt'
            dest = source_root / package / (digest + safe_suffix)
            dest.parent.mkdir(parents=True, exist_ok=True)
            if not dest.exists():
                dest.write_bytes(data)
            row['source_file'] = str(dest.relative_to(source_root.parent))
            record['retained_source_files'] += 1
    if zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as archive:
            for member in archive.infolist():
                if member.is_dir():
                    continue
                mode = stat.S_IFMT(member.external_attr >> 16)
                if mode not in (0, stat.S_IFREG):
                    record['links'].append({'path': member.filename, 'kind': 'zip_nonregular', 'mode': mode})
                    continue
                consume(member.filename, member.file_size, lambda m=member: archive.open(m))
    else:
        with tarfile.open(path, 'r|*') as archive:
            for member in archive:
                if member.isfile():
                    consume(member.name, member.size, lambda m=member: archive.extractfile(m))
                elif member.issym() or member.islnk():
                    record['links'].append({'path': member.name, 'target': member.linkname, 'kind': 'symlink' if member.issym() else 'hardlink'})
    record['filter_counts'] = dict(filtered)
    record['status'] = 'partial_scan' if record['skipped_members'] else 'scanned'
    return record

class SafeRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        validate_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)

def validate_url(url):
    parsed = urllib.parse.urlsplit(url)
    if parsed.scheme != 'https' or parsed.hostname != 'files.pythonhosted.org' or parsed.username or parsed.password or parsed.port not in (None, 443):
        raise ValueError('only public HTTPS files.pythonhosted.org source URLs are allowed')

class Downloader:
    def __init__(self, interval, attempts):
        self.interval = interval
        self.attempts = attempts
        self.lock = threading.Lock()
        self.next_request = 0.0
        self.opener = urllib.request.build_opener(SafeRedirect())
    def open(self, url):
        validate_url(url)
        for attempt in range(self.attempts):
            with self.lock:
                delay = max(0.0, self.next_request - time.monotonic())
                self.next_request = max(self.next_request, time.monotonic()) + self.interval
            if delay:
                time.sleep(delay)
            try:
                req = urllib.request.Request(url, headers={'User-Agent': 'frozen-static-unicode-survey/1.0 (source-only; no builds)'})
                return self.opener.open(req, timeout=90)
            except urllib.error.HTTPError as error:
                if error.code not in (429,500,502,503,504) or attempt + 1 == self.attempts:
                    raise
                try:
                    delay = float(error.headers.get('Retry-After', 2 ** attempt))
                except (TypeError, ValueError):
                    delay = 2 ** attempt
            except (OSError, TimeoutError):
                if attempt + 1 == self.attempts:
                    raise
                delay = 2 ** attempt
            time.sleep(min(60.0, max(0.0, delay)))
        raise RuntimeError('download retry budget exhausted')
    def download(self, row, target):
        expected = row['current_sdist_sha256']
        size = row['current_sdist_size']
        if target.exists() and target.stat().st_size == size and file_hash(target) == expected:
            return
        target.unlink(missing_ok=True)
        partial = target.with_suffix('.part')
        try:
            digest = hashlib.sha256()
            received = 0
            with self.open(row['current_sdist_url']) as response, partial.open('wb') as stream:
                while chunk := response.read(1024 * 1024):
                    received += len(chunk)
                    if received > size:
                        raise ValueError('download exceeds frozen declared sdist size')
                    digest.update(chunk)
                    stream.write(chunk)
            if digest.hexdigest() != expected or received != size:
                raise ValueError('download SHA256/size differs from frozen sdist')
            partial.replace(target)
        finally:
            partial.unlink(missing_ok=True)

def fingerprint(row, args):
    return {'format_version': FORMAT_VERSION, 'row_sha256': hashlib.sha256(json.dumps(row, sort_keys=True).encode()).hexdigest(),
            'retain_source': args.retain_source, 'max_member_mib': args.max_member_mib}

def process(row, args, downloader):
    package = row['package']
    result_path = args.output / 'results' / (package + '.json')
    config = fingerprint(row, args)
    if result_path.exists() and not args.retry:
        previous = json.loads(result_path.read_bytes())
        if previous.get('run_fingerprint') != config:
            raise ValueError('resume settings/frozen row differ; choose new --output or --retry: ' + package)
        return previous
    result = {'rank': row['rank'], 'package': package, 'version': row['version'], 'frozen_status': row['status'],
              'started_utc': utc(), 'run_fingerprint': config}
    if not row['current_sdist_url']:
        result.update(status=row['status'], unavailable_reason=row.get('unavailable_reason'), source_coverage='unavailable; never interpreted as zero')
        save_json(result_path, result)
        return result
    archive = args.output / 'downloads' / (package + '-' + row['current_sdist_sha256'])
    archive.parent.mkdir(parents=True, exist_ok=True)
    try:
        downloader.download(row, archive)
        result['archive_verified_sha256'] = row['current_sdist_sha256']
        result.update(scan_archive(archive, package, row['version'], args.retain_source, args.output / 'sources', args.max_member_mib * 1024**2))
    except Exception as error:
        result.update(status='failed', error=type(error).__name__ + ': ' + str(error))
    finally:
        if not args.keep_archives:
            archive.unlink(missing_ok=True)
        archive.with_suffix('.part').unlink(missing_ok=True)
    result['completed_utc'] = utc()
    save_json(result_path, result)
    return result

def aggregate(output):
    records = sorted((json.loads(p.read_bytes()) for p in (output / 'results').glob('*.json')), key=lambda r: r['rank'])
    counts = {mode + '/' + scope: {} for mode in ('all', 'canonical_default', 'canonical_cython') for scope in ('expanded', 'original_write')}
    with (output / 'hits.jsonl').open('w', encoding='utf-8') as hits_out, (output / 'candidate-files.jsonl').open('w', encoding='utf-8') as files_out:
        for row in records:
            for hit in row.get('hits', []):
                hits_out.write(json.dumps(hit, ensure_ascii=False) + '\n')
                for mode in ('all', 'canonical_default', 'canonical_cython'):
                    if mode != 'all' and not hit[mode + '_included']:
                        continue
                    for scope in ('expanded', 'original_write'):
                        if scope == 'original_write' and not hit['original_write_scope']:
                            continue
                        table = counts.setdefault(mode + '/' + scope, {})
                        value = table.setdefault(hit['symbol'], {'raw_token_occurrences': 0, 'call_expression_occurrences': 0, 'direct_call_occurrences': 0, 'macro_body_occurrences': 0, 'packages': set(), 'kinds': collections.Counter()})
                        value['raw_token_occurrences'] += 1
                        value['kinds'][hit['kind']] += 1
                        if hit['kind'] in ('call_like', 'macro_body_call'):
                            value['call_expression_occurrences'] += 1
                            value['packages'].add(row['package'])
                            value['direct_call_occurrences' if hit['kind'] == 'call_like' else 'macro_body_occurrences'] += 1
            for candidate in row.get('candidate_files', []):
                files_out.write(json.dumps(candidate, ensure_ascii=False) + '\n')
    for table_key, table in counts.items():
        for value in table.values():
            value['package_count'] = len(value['packages'])
            value['packages'] = sorted(value['packages'])
            value['kinds'] = dict(value['kinds'])
        # Explicit zero rows keep absent APIs distinguishable from unavailable packages.
        scope_symbols = PRIMARY + ORIGINAL_READ + (EXPANDED_READ if table_key.endswith('/expanded') else [])
        for symbol in scope_symbols:
            table.setdefault(symbol, {'raw_token_occurrences': 0, 'call_expression_occurrences': 0, 'direct_call_occurrences': 0, 'macro_body_occurrences': 0, 'package_count': 0, 'packages': [], 'kinds': {}})
    summary = {'classified': len(records), 'scope': 'selected frozen metadata rows; see coverage.csv',
               'statuses': dict(collections.Counter(r['status'] for r in records)),
               'files_inspected': sum(r.get('files_inspected', 0) for r in records),
               'retained_source_files': sum(r.get('retained_source_files', 0) for r in records),
               'lexical_counts': counts, 'updated_utc': utc()}
    save_json(output / 'summary.json', summary)
    save_json(output / 'coverage-exceptions.json', [{k:v for k,v in r.items() if k not in ('hits','candidate_files','native_files')} for r in records if r['status'] != 'scanned'])
    with (output / 'coverage.csv').open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=['rank','package','version','frozen_status','status','files_inspected','regular_members','declared_bytes','error'], extrasaction='ignore')
        writer.writeheader()
        writer.writerows(records)
    return summary

def load_metadata(path):
    rows = [json.loads(line) for line in path.read_text(encoding='utf-8').splitlines() if line]
    if len({row['rank'] for row in rows}) != len(rows) or len({row['package'] for row in rows}) != len(rows):
        raise ValueError('duplicate rank/package in metadata')
    for row in rows:
        if not re.fullmatch(r'[A-Za-z0-9_.-]+', row['package']):
            raise ValueError('unsafe package name')
        if row['current_sdist_url']:
            validate_url(row['current_sdist_url'])
            filename = row.get('current_sdist_filename', '')
            if not filename or filename.lower().endswith('.whl') or urllib.parse.urlsplit(row['current_sdist_url']).path.lower().endswith('.whl'):
                raise ValueError('only source-distribution metadata is accepted; wheels are forbidden')
            if not re.fullmatch(r'[0-9a-f]{64}', row['current_sdist_sha256']) or not isinstance(row['current_sdist_size'], int) or row['current_sdist_size'] < 0:
                raise ValueError('invalid frozen sdist digest/size')
            if row['archive_verified_sha256'] != row['current_sdist_sha256']:
                raise ValueError('frozen archive was not verified')
    return sorted(rows, key=lambda r:r['rank'])

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--metadata', type=Path, default=PUB / 'data/source-metadata.jsonl')
    parser.add_argument('--output', type=Path, default=PUB / 'scan-output')
    parser.add_argument('--download', action='store_true', help='explicitly download frozen public sdists; otherwise plan only')
    parser.add_argument('--limit', type=int, default=4000, help='number of ranks starting at --start-rank')
    parser.add_argument('--start-rank', type=int, default=1)
    parser.add_argument('--packages', nargs='*')
    parser.add_argument('--workers', type=int, default=2)
    parser.add_argument('--request-interval', type=float, default=0.25, help='global minimum request spacing, seconds')
    parser.add_argument('--attempts', type=int, default=4)
    parser.add_argument('--retry', action='store_true', help='rescan selected completed/failed records; default resumes by package')
    parser.add_argument('--retain-source', choices=['none','candidates','native'], default='none')
    parser.add_argument('--keep-archives', action='store_true')
    parser.add_argument('--max-member-mib', type=int, default=128)
    parser.add_argument('--aggregate-only', action='store_true')
    args = parser.parse_args()
    if args.limit < 1 or args.start_rank < 1 or args.workers < 1 or args.attempts < 1 or args.request_interval < 0 or args.max_member_mib < 1:
        parser.error('limits, ranks, workers and attempts must be positive; interval cannot be negative')
    rows = load_metadata(args.metadata)
    rows = [r for r in rows if args.start_rank <= r['rank'] < args.start_rank + args.limit]
    if args.packages:
        chosen = set(args.packages)
        unknown = chosen - {r['package'] for r in rows}
        if unknown:
            parser.error('packages outside selected rank interval: ' + ', '.join(sorted(unknown)))
        rows = [r for r in rows if r['package'] in chosen]
    if args.aggregate_only:
        args.output.mkdir(parents=True, exist_ok=True)
        summary = aggregate(args.output)
        print(json.dumps({k:v for k,v in summary.items() if k != 'lexical_counts'}))
        return
    if not args.download:
        print(json.dumps({'mode': 'plan_only_no_network', 'selected_rows': len(rows),
                          'sdists': sum(bool(r['current_sdist_url']) for r in rows),
                          'declared_download_bytes': sum(r['current_sdist_size'] or 0 for r in rows),
                          'frozen_statuses': dict(collections.Counter(r['status'] for r in rows))}, indent=2))
        return
    args.output.mkdir(parents=True, exist_ok=True)
    downloader = Downloader(args.request_interval, args.attempts)
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as pool:
        tasks = [pool.submit(process, row, args, downloader) for row in rows]
        for task in concurrent.futures.as_completed(tasks):
            result = task.result()
            print(result['rank'], result['package'], result['status'], flush=True)
    summary = aggregate(args.output)
    print(json.dumps({k:v for k,v in summary.items() if k != 'lexical_counts'}))

if __name__ == '__main__':
    main()
