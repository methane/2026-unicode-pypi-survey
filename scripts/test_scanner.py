#!/usr/bin/env python3
"""Offline stdlib tests: synthetic archives only; no third-party code execution."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import stat
import tarfile
import tempfile
import unittest
import zipfile
import scan_sdists as scan

class ScannerTests(unittest.TestCase):
    def test_tar_safety_lexical_filters_and_retention(self):
        source = b'/* PyUnicode_New is mentioned */\nvoid run() { PyUnicode_New(1, 127); }\n#define WRITE(o,k,d,i,c) PyUnicode_WRITE(k,d,i,c)\n'
        generated = b'/* Generated by Cython 3.0.1 */\nPyUnicode_READ_CHAR(obj, 0);\n'
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary)
            archive = base / 'source.tar.gz'
            with tarfile.open(archive, 'w:gz') as output:
                for name, data in [('demo/a.c', source), ('demo/cython.c', generated),
                                   ('demo/pythoncapi_compat.h', b'PyUnicode_ReadChar(s, i);'),
                                   ('demo/readme.rst', b'PyUnicode_New(1, 127);'),
                                   ('demo/a.js.map', b'PyUnicode_New(1, 127);'),
                                   ('demo/plain.map', b'PyUnicode_New(1, 127);'),
                                   ('demo/binary.c', b'\x00PyUnicode_New(1,127);'),
                                   ('../outside.c', b'PyUnicode_New(1, 127);')]:
                    member = tarfile.TarInfo(name)
                    member.size = len(data)
                    output.addfile(member, io.BytesIO(data))
                link = tarfile.TarInfo('demo/link.c')
                link.type = tarfile.SYMTYPE
                link.linkname = '../../outside'
                output.addfile(link)
            result = scan.scan_archive(archive, 'demo')
            self.assertEqual(result['status'], 'partial_scan')
            self.assertEqual(result['skipped_members'][0]['reason'], 'unsafe_member_name')
            self.assertEqual(len(result['links']), 1)
            self.assertFalse((base / 'sources').exists())
            self.assertEqual(result['retained_source_files'], 0)
            h = [hit for hit in result['hits'] if hit['path'] == 'demo/a.c']
            self.assertEqual([(x['line'], x['kind']) for x in h], [(1, 'comment_or_string'), (2, 'call_like'), (3, 'macro_body_call')])
            self.assertTrue(all(x['canonical_default_included'] for x in h))
            g = next(x for x in result['hits'] if x['path'] == 'demo/cython.c')
            self.assertFalse(g['canonical_default_included'])
            self.assertTrue(g['canonical_cython_included'])
            c = next(x for x in result['hits'] if x['path'].endswith('pythoncapi_compat.h'))
            self.assertFalse(c['canonical_default_included'])
            self.assertFalse(c['canonical_cython_included'])
            self.assertTrue(any(x['path'] == 'demo/plain.map' for x in result['hits']))
            self.assertFalse(any(x['path'].endswith(('.rst', '.js.map', 'binary.c')) for x in result['hits']))
            retained = scan.scan_archive(archive, 'demo', retain='native', source_root=base / 'sources')
            for row in retained['native_files']:
                if 'source_file' in row:
                    path = base / row['source_file']
                    self.assertEqual(scan.file_hash(path), row['sha256'])
            self.assertFalse((base.parent / 'outside.c').exists())
    def test_zip_nonregular_and_limit(self):
        with tempfile.TemporaryDirectory() as temporary:
            archive = Path(temporary) / 'source.zip'
            with zipfile.ZipFile(archive, 'w') as output:
                output.writestr('demo/a.c', b'PyUnicode_ReadChar(o, 0);')
                output.writestr('demo/too-big.c', b'x' * 100)
                symlink = zipfile.ZipInfo('demo/link.c')
                symlink.create_system = 3
                symlink.external_attr = (stat.S_IFLNK | 0o777) << 16
                output.writestr(symlink, '../outside')
            result = scan.scan_archive(archive, 'demo', max_member_bytes=50)
            self.assertEqual(len(result['hits']), 1)
            self.assertEqual(result['hits'][0]['symbol'], 'PyUnicode_ReadChar')
            self.assertFalse(result['hits'][0]['original_write_scope'])
            self.assertEqual(result['skipped_members'][0]['reason'], 'text_member_size_limit')
            self.assertEqual(len(result['links']), 1)
    def test_resume_frozen_unavailable_no_network(self):
        with tempfile.TemporaryDirectory() as temporary:
            args = argparse.Namespace(output=Path(temporary), retry=False, retain_source='none', max_member_mib=128, keep_archives=False)
            row = {'rank': 1, 'package': 'demo', 'version': None, 'status': 'metadata_unavailable', 'current_sdist_url': None, 'unavailable_reason': 'frozen metadata HTTP404'}
            first = scan.process(row, args, None)
            second = scan.process(row, args, None)
            self.assertEqual(first, second)
            summary = scan.aggregate(args.output)
            self.assertEqual(summary['statuses'], {'metadata_unavailable': 1})
            self.assertEqual(summary['retained_source_files'], 0)
            args.retain_source = 'native'
            with self.assertRaisesRegex(ValueError, 'resume settings'):
                scan.process(row, args, None)
    def test_cached_hash_verified_and_bad_url(self):
        with tempfile.TemporaryDirectory() as temporary:
            path = Path(temporary) / 'archive'
            data = b'cached-source-archive'
            path.write_bytes(data)
            row = {'current_sdist_sha256': hashlib.sha256(data).hexdigest(), 'current_sdist_size': len(data)}
            scan.Downloader(0.25, 1).download(row, path)
            self.assertEqual(path.read_bytes(), data)
        for url in ['http://files.pythonhosted.org/a', 'https://example.org/a', 'https://files.pythonhosted.org:444/a', 'file:///tmp/a']:
            with self.assertRaises(ValueError):
                scan.validate_url(url)
    def test_raw_layout_is_candidate_not_presumed_read(self):
        result = scan.scan_text(b'PyASCIIObject *p;\n', 'demo/type.h', 'demo', None)
        self.assertEqual(result, [])

if __name__ == '__main__':
    unittest.main()
