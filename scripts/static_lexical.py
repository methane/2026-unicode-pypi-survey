"""Offset-preserving static lexical heuristics adapted from the original survey.
Only analysis code is imported; package source is never imported.
"""
import re

CODE_EXT = {'.c', '.h', '.cc', '.cpp', '.cxx', '.hpp', '.hxx', '.inc', '.pxd', '.pyx',
            '.pxi', '.rs', '.go', '.m', '.mm', '.swift', '.py', '.i'}

C_MASK = re.compile(r'/\*[\s\S]*?\*/|//[^\n]*|(?:u8|u|U|L)?R"(?P<delimiter>[^\s()\\]{0,16})\([\s\S]*?\)(?P=delimiter)"|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')

PY_MASK = re.compile(r'\#[^\n]*|"""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\'|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')

RUST_MASK = re.compile(r'/\*[\s\S]*?\*/|//[^\n]*|r(?P<hashes>\#{0,32})"[\s\S]*?"(?P=hashes)|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\(?:u\{[0-9a-fA-F]+\}|x[0-9a-fA-F]{2}|[^\n])|[^\'\\\n])\'')

def mask_source(text, suffix):
    pat = (PY_MASK if suffix in {'.py', '.pyx', '.pxd', '.pxi'} else
           RUST_MASK if suffix == '.rs' else C_MASK)
    if suffix != '.rs':
        return pat.sub(lambda m: re.sub(r'[^\n]', ' ', m.group()), text)
    parts=[]; cursor=0
    for m in pat.finditer(text):
        if m.start() < cursor: continue
        end=m.end()
        if text.startswith('/*',m.start()):
            depth=0;end=len(text)
            for c in re.finditer(r'/\*|\*/',text[m.start():]):
                depth += 1 if c.group()=='/*' else -1
                if depth==0:
                    end=m.start()+c.end();break
        parts.append(text[cursor:m.start()])
        parts.append(re.sub(r'[^\n]',' ',text[m.start():end]))
        cursor=end
    parts.append(text[cursor:])
    return ''.join(parts)

def origin(path, text):
    head = text[:12000]
    if '/Cython/Utility/' in path or '/Cython/Includes/' in path:
        return 'generator_runtime'
    if '/_generated_include/' in path:
        return 'generated_other'
    if re.search(r'Generated by Cython|CYTHON_ABI|__PYX_HAVE__', head):
        return 'generated_cython'
    if re.search(r'generated (?:file|code)|automatically generated|DO NOT EDIT', head, re.I):
        return 'generated_other'
    if re.search(r'pythoncapi[_-]compat|py3c/|python_compat|pythoncompat', path, re.I):
        return 'compatibility'
    if re.search(r'(^|/)(?:cpython_src|cpython-source)(/|$)', path, re.I):
        return 'vendor_cpython'
    if '/include/cpython/' in path:
        return 'vendor_cpython'
    if re.search(r'(^|/)typed_ast-[^/]+/ast(?:27|3)/|/backports/datetime_fromisoformat/_datetimemodule\.c$',path):
        return 'cpython_fork_backport'
    if '/spacy/matcher/polyleven.c' in path:
        return 'vendor'
    if re.search(r'(^|/)(?:_?vendor(?:ed)?|third[_-]?party|externals?|extern|deps|boost|cargo)(/|$)', path, re.I):
        return 'vendor'
    if '/src/ffi/cpython/' in path:
        return 'compatibility_binding'
    return 'handwritten_candidate'

def kind_of(text, masked, start, end, suffix):
    if suffix not in CODE_EXT:
        return 'non_code'
    if not masked[start:end].strip():
        return 'comment_or_string'
    line_start = masked.rfind('\n', 0, start) + 1
    line_end = masked.find('\n', end)
    line = masked[line_start:line_end if line_end >= 0 else len(masked)]
    macro_context = line
    prev_start = line_start
    for _ in range(64):
        prev_end = prev_start - 1
        if prev_end < 0: break
        prior_start = masked.rfind('\n',0,prev_end) + 1
        previous = masked[prior_start:prev_end]
        if not previous.rstrip().endswith('\\'): break
        macro_context = previous + '\n' + macro_context
        prev_start = prior_start
    if re.match(r'\s*#\s*define\s+' + re.escape(masked[start:end]) + r'\b', line):
        return 'macro_definition'
    tail = masked[end:end+4096]
    if not re.match(r'\s*\(', tail):
        return 'reference'
    if re.match(r'\s*#\s*define\b', macro_context):
        return 'macro_body_call'
    # A C/C++ declaration has a type prefix, balanced parameters and ; or { after it.
    op = end + re.match(r'\s*', tail).end()
    depth = 0; close = None
    for pos in range(op, min(len(masked), op + 4096)):
        if masked[pos] == '(':
            depth += 1
        elif masked[pos] == ')':
            depth -= 1
            if depth == 0:
                close = pos; break
    prefix = masked[line_start:start].strip()
    if suffix == '.py' and re.fullmatch(r'(?:async\s+)?def',prefix):
        return 'declaration_definition'
    if not prefix and suffix in {'.c', '.h', '.cc', '.cpp', '.cxx', '.hpp', '.hxx', '.inc'}:
        prior_end = line_start
        while prior_end and masked[prior_end-1].isspace(): prior_end -= 1
        prior_start = masked.rfind('\n', 0, prior_end) + 1
        prefix = masked[prior_start:prior_end].strip()
    if suffix == '.rs' and re.search(r'\bfn\s*$', prefix):
        return 'declaration_definition'
    cython_control = {'return','yield','raise','await','assert','if','elif','while','for','not'}
    if suffix in {'.pxd', '.pyx', '.pxi'} and re.search(r'^(?:cdef\s+)?(?:extern\s+)?[\w* ]+\s$', masked[line_start:start]) and '=' not in prefix and not any(word in cython_control for word in prefix.split()):
        return 'declaration_definition'
    is_type = re.fullmatch(r'(?:(?:extern|static|inline|const|unsigned|signed)\s+)*(?:[A-Za-z_]\w*\s*\**\s+|[A-Za-z_]\w*\s*\*+\s*)', prefix + ' ') or re.fullmatch(r'Py(?:API_FUNC|_LOCAL_INLINE|_LOCAL)\([^\n]+\)',prefix)
    if close is not None and re.match(r'\s*(?:;|\{)', masked[close+1:close+201]) and is_type and prefix not in {'return', 'co_return', 'else', 'break', 'continue', 'goto', 'throw'}:
        return 'declaration_definition'
    return 'call_like'
